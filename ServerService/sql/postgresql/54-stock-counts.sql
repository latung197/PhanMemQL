-- Kho: phiếu kiểm kê (đối chiếu tồn sổ sách với tồn thực tế của một kho tại một ngày). Chạy lại được; chạy sau 34 (sổ kho) và 43.
-- Phiếu kiểm kê đi qua quy trình duyệt như mọi chứng từ và GHI SỔ KHO: dòng thừa (thực tế > sổ sách) nhập thêm vào kho theo giá
-- bình quân, dòng thiếu xuất khỏi kho theo giá bình quân; ghi sổ qua IStockLedger, không có SQL riêng vào sổ kho.
-- Tồn sổ sách của mỗi dòng không do người dùng nhập: máy chủ tính từ sổ kho tại ngày kiểm kê mỗi lần lưu và lúc ghi sổ.
-- Không khóa ngoại theo quy ước dự án.
CREATE TABLE IF NOT EXISTS erp_stock_count (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    warehouse_code varchar(20) NOT NULL,
    counter_name varchar(200),
    reason varchar(300),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    surplus_value numeric(18,2) NOT NULL DEFAULT 0,
    shortage_value numeric(18,2) NOT NULL DEFAULT 0,
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_stock_count_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled'))
);
CREATE INDEX IF NOT EXISTS ix_erp_stock_count_unit_date ON erp_stock_count (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_stock_count_warehouse_code ON erp_stock_count (warehouse_code);

CREATE TABLE IF NOT EXISTS erp_stock_count_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    count_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    lot_number varchar(64),
    position varchar(100),
    book_quantity numeric(18,4) NOT NULL DEFAULT 0,
    counted_quantity numeric(18,4) NOT NULL DEFAULT 0,
    diff_quantity numeric(18,4) NOT NULL DEFAULT 0,
    unit_cost numeric(18,4) NOT NULL DEFAULT 0,
    diff_value numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_stock_count_line_counted CHECK (counted_quantity >= 0),
    CONSTRAINT ck_erp_stock_count_line_cost CHECK (unit_cost >= 0),
    UNIQUE (count_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_stock_count_line_count ON erp_stock_count_line (count_id);
CREATE INDEX IF NOT EXISTS ix_erp_stock_count_line_material_code ON erp_stock_count_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_stock_count_line_uom_code ON erp_stock_count_line (uom_code);
