-- Kho: điều chuyển kho giữa hai kho của cùng một đơn vị cơ sở: Lệnh điều chuyển (LDC) → Phiếu xuất điều chuyển (PXDC) →
-- Phiếu nhập điều chuyển (PNDC). Chạy lại được; chạy sau 41 và 42.
-- Lệnh điều chuyển KHÔNG ghi sổ kho. Phiếu xuất điều chuyển ghi sổ XUẤT ở kho đi (sổ kho tính giá bình quân); phiếu nhập điều chuyển
-- ghi sổ NHẬP ở kho đến theo đúng giá trị của phiếu xuất. Phiếu xuất "lấy từ lệnh" (transfer_order_line_id), phiếu nhập BẮT BUỘC lấy từ
-- phiếu xuất đã ghi sổ (transfer_issue_line_id); số đã chuyển / đã nhận của một dòng luôn tính từ chứng từ sau chưa hủy, không lưu cột riêng.
-- Không khóa ngoại theo quy ước dự án.

CREATE TABLE IF NOT EXISTS erp_transfer_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    required_date date,
    from_warehouse_code varchar(20) NOT NULL,
    to_warehouse_code varchar(20) NOT NULL,
    reason varchar(100) NOT NULL,
    person_name varchar(200),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_transfer_order_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_transfer_order_warehouses CHECK (from_warehouse_code <> to_warehouse_code)
);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_unit_date ON erp_transfer_order (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_from_warehouse_code ON erp_transfer_order (from_warehouse_code);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_to_warehouse_code ON erp_transfer_order (to_warehouse_code);

CREATE TABLE IF NOT EXISTS erp_transfer_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_transfer_order_line_quantity CHECK (quantity > 0),
    UNIQUE (order_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_line_order_id ON erp_transfer_order_line (order_id);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_line_material_code ON erp_transfer_order_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_transfer_order_line_uom_code ON erp_transfer_order_line (uom_code);

