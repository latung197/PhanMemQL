-- Xóa phiếu xuất / nhập điều chuyển thì xóa dòng chi tiết và dấu vết sổ kho (cùng trigger với phiếu nhập / xuất kho, xem 41).
DROP TRIGGER IF EXISTS trg_erp_transfer_issue_delete ON erp_transfer_issue;
CREATE TRIGGER trg_erp_transfer_issue_delete BEFORE DELETE ON erp_transfer_issue
    FOR EACH ROW EXECUTE FUNCTION erp_voucher_delete_cleanup('inv_transfer_issue', 'erp_transfer_issue_line', 'issue_id');
DROP TRIGGER IF EXISTS trg_erp_transfer_receipt_delete ON erp_transfer_receipt;
CREATE TRIGGER trg_erp_transfer_receipt_delete BEFORE DELETE ON erp_transfer_receipt
    FOR EACH ROW EXECUTE FUNCTION erp_voucher_delete_cleanup('inv_transfer_receipt', 'erp_transfer_receipt_line', 'receipt_id');
