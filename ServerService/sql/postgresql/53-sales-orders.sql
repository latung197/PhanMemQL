-- Bán hàng: đơn bán hàng (sales_orders, số SO) và phiếu xuất kho lấy hàng từ đơn bán. Chạy lại được; chạy sau 52. Không khóa ngoại.
--   * Đơn bán hàng không ghi sổ kho (trạng thái dừng ở Đã duyệt); phiếu xuất kho (inv_issue) lấy dòng của đơn đã duyệt:
--     erp_goods_issue_line.sales_order_line_id là sự thật, erp_goods_issue.sales_order_code là danh sách số đơn suy từ các dòng.
--   * Số lượng đã xuất của một dòng đơn tính từ các dòng phiếu xuất trỏ tới nó trên phiếu chưa hủy, không lưu ở đơn.
--   * Phiếu xuất có thêm mã khách hàng (customer_code) trỏ danh mục khách hàng, tùy chọn: phiếu xuất tự do vẫn dùng tên khách tự gõ.
CREATE TABLE IF NOT EXISTS erp_sales_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    delivery_date date,
    warehouse_code varchar(20) NOT NULL,
    voucher_type varchar(100) NOT NULL,
    customer_code varchar(20) NOT NULL,
    customer_name varchar(200),
    delivery_address varchar(300),
    payment_terms varchar(200),
    payment_term_code varchar(20),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    tax_rate_code varchar(20),
    tax_rate numeric(7,4) NOT NULL DEFAULT 0,
    sub_total numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    project_code varchar(20),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_sales_order_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_sales_order_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_unit_date ON erp_sales_order (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_warehouse_code ON erp_sales_order (warehouse_code);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_customer_code ON erp_sales_order (customer_code);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_currency_code ON erp_sales_order (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_tax_rate_code ON erp_sales_order (tax_rate_code) WHERE tax_rate_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_payment_term_code ON erp_sales_order (payment_term_code) WHERE payment_term_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_project_code ON erp_sales_order (project_code) WHERE project_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS erp_sales_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_sales_order_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_sales_order_line_price CHECK (unit_price >= 0),
    UNIQUE (order_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_line_order ON erp_sales_order_line (order_id);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_line_material_code ON erp_sales_order_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_sales_order_line_uom_code ON erp_sales_order_line (uom_code);

-- Phiếu xuất kho lấy từ đơn bán hàng
ALTER TABLE erp_goods_issue ADD COLUMN IF NOT EXISTS customer_code varchar(20);
ALTER TABLE erp_goods_issue ADD COLUMN IF NOT EXISTS sales_order_code varchar(500);
ALTER TABLE erp_goods_issue_line ADD COLUMN IF NOT EXISTS sales_order_line_id bigint;
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_customer_code ON erp_goods_issue (customer_code) WHERE customer_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_line_sales_order_line_id ON erp_goods_issue_line (sales_order_line_id) WHERE sales_order_line_id IS NOT NULL;
