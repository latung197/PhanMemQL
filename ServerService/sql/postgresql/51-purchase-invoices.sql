-- Mua hàng: hóa đơn mua hàng (pur_invoice, số HDM) = hóa đơn của nhà cung cấp, là căn cứ công nợ phải trả.
-- Chạy lại được; chạy sau 44 (đơn mua hàng) và 45 (điều khoản thanh toán). Không khóa ngoại.
--   * Hóa đơn không ghi sổ kho: dòng của nó lấy từ dòng phiếu nhập kho (goods_receipt_line_id) và / hoặc dòng đơn mua hàng
--     (purchase_order_line_id); số lượng đã lên hóa đơn của một dòng nguồn tính từ các hóa đơn chưa hủy, không lưu ở nguồn.
--   * invoice_no / invoice_series / invoice_date là số, ký hiệu, ngày ghi trên hóa đơn giấy hoặc điện tử của nhà cung cấp;
--     due_date là hạn thanh toán (ngày hóa đơn + số ngày của điều khoản thanh toán, hoặc nhập tay).
CREATE TABLE IF NOT EXISTS erp_purchase_invoice (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    voucher_type varchar(100) NOT NULL,
    supplier_code varchar(20) NOT NULL,
    supplier_name varchar(200),
    invoice_no varchar(50) NOT NULL,
    invoice_series varchar(30),
    invoice_date date NOT NULL,
    due_date date NOT NULL,
    payment_terms varchar(200),
    payment_term_code varchar(20),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    tax_rate_code varchar(20),
    tax_rate numeric(7,4) NOT NULL DEFAULT 0,
    sub_total numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    purchase_order_code varchar(500),
    goods_receipt_code varchar(500),
    project_code varchar(20),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_invoice_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_purchase_invoice_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_unit_date ON erp_purchase_invoice (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_supplier_code ON erp_purchase_invoice (supplier_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_currency_code ON erp_purchase_invoice (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_tax_rate_code ON erp_purchase_invoice (tax_rate_code) WHERE tax_rate_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_payment_term_code ON erp_purchase_invoice (payment_term_code) WHERE payment_term_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_project_code ON erp_purchase_invoice (project_code) WHERE project_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_supplier_invoice ON erp_purchase_invoice (supplier_code, invoice_no);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_due ON erp_purchase_invoice (unit_code, due_date) WHERE status = 'Approved';

CREATE TABLE IF NOT EXISTS erp_purchase_invoice_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    purchase_order_line_id bigint,
    goods_receipt_line_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_invoice_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_purchase_invoice_line_price CHECK (unit_price >= 0),
    UNIQUE (invoice_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_line_invoice ON erp_purchase_invoice_line (invoice_id);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_line_material_code ON erp_purchase_invoice_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_line_uom_code ON erp_purchase_invoice_line (uom_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_line_order_line ON erp_purchase_invoice_line (purchase_order_line_id) WHERE purchase_order_line_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_purchase_invoice_line_receipt_line ON erp_purchase_invoice_line (goods_receipt_line_id) WHERE goods_receipt_line_id IS NOT NULL;
