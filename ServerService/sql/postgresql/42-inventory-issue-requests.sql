-- Kho: phiếu yêu cầu xuất kho (bộ phận đề nghị kho xuất hàng) và liên kết từ phiếu xuất kho. Chạy lại được; chạy sau 39 và 40.
-- Phiếu yêu cầu đi qua quy trình duyệt như mọi chứng từ nhưng KHÔNG ghi sổ kho (chỉ phiếu xuất kho mới làm đổi tồn).
-- Phiếu xuất kho "lấy dữ liệu" từ một phiếu yêu cầu đã duyệt: đầu phiếu ghi issue_request_code, mỗi dòng ghi
-- issue_request_line_id (dòng yêu cầu mà nó thực hiện). Số đã xuất của một dòng yêu cầu = tổng số lượng các dòng phiếu xuất
-- trỏ tới nó, của phiếu xuất chưa hủy (không lưu cột riêng, luôn tính từ phiếu xuất). Không khóa ngoại theo quy ước dự án.
CREATE TABLE IF NOT EXISTS erp_issue_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    required_date date,
    warehouse_code varchar(20) NOT NULL,
    voucher_type varchar(100) NOT NULL,
    department_code varchar(20),
    requester_name varchar(200),
    customer_name varchar(200),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_issue_request_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_issue_request_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_unit_date ON erp_issue_request (unit_code, document_date DESC);
-- Mỗi cột *_code trỏ danh mục khác có chỉ mục bắt đầu bằng chính cột đó.
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_warehouse_code ON erp_issue_request (warehouse_code);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_currency_code ON erp_issue_request (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_department_code ON erp_issue_request (department_code) WHERE department_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS erp_issue_request_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_issue_request_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_issue_request_line_price CHECK (unit_price >= 0),
    UNIQUE (request_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_line_request ON erp_issue_request_line (request_id);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_line_material_code ON erp_issue_request_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_issue_request_line_uom_code ON erp_issue_request_line (uom_code);

-- Phiếu xuất kho lấy từ phiếu yêu cầu.
ALTER TABLE erp_goods_issue ADD COLUMN IF NOT EXISTS issue_request_code varchar(500);
ALTER TABLE erp_goods_issue_line ADD COLUMN IF NOT EXISTS issue_request_line_id bigint;
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_issue_request_code ON erp_goods_issue (issue_request_code) WHERE issue_request_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_line_issue_request_line_id ON erp_goods_issue_line (issue_request_line_id) WHERE issue_request_line_id IS NOT NULL;

-- Một phiếu xuất có thể lấy từ nhiều phiếu yêu cầu: issue_request_code là danh sách mã cách nhau bằng dấu phẩy.
ALTER TABLE erp_goods_issue ALTER COLUMN issue_request_code TYPE varchar(500);
