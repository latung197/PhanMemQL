-- Kế toán: hệ thống tài khoản kế toán (Thông tư 200/2014/TT-BTC) và tài khoản thuế của mã thuế. Chạy lại được; chạy sau 49.
-- erp_account: danh mục tài khoản nhiều cấp (cha - con). Tài khoản cha chỉ để cộng dồn; chỉ tài khoản lá (không có con) mới
-- hạch toán được. Mã tài khoản con bắt đầu bằng mã tài khoản cha (133 -> 1331 -> 13311). Không khóa ngoại theo quy ước dự án.
CREATE TABLE IF NOT EXISTS erp_account (
    code varchar(20) PRIMARY KEY,
    name varchar(200) NOT NULL,
    name_en varchar(200),
    parent_account_code varchar(20),
    level integer NOT NULL DEFAULT 1,
    account_type varchar(20) NOT NULL,
    nature varchar(10) NOT NULL,
    note varchar(300),
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_account_type CHECK (account_type IN ('ASSET','LIABILITY','EQUITY','REVENUE','COST','OTHER_INCOME','OTHER_EXPENSE','PROFIT_LOSS','OFF_BALANCE')),
    CONSTRAINT ck_erp_account_nature CHECK (nature IN ('DEBIT','CREDIT','BOTH'))
);
CREATE INDEX IF NOT EXISTS ix_erp_account_parent_account_code ON erp_account (parent_account_code) WHERE parent_account_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_account_type ON erp_account (account_type);

-- Mã thuế trỏ tới tài khoản thuế đầu vào (ví dụ 1331) và đầu ra (ví dụ 33311); chỉ chọn được tài khoản lá.
ALTER TABLE sys_tax_rate ADD COLUMN IF NOT EXISTS input_account_code varchar(20);
ALTER TABLE sys_tax_rate ADD COLUMN IF NOT EXISTS output_account_code varchar(20);
CREATE INDEX IF NOT EXISTS ix_sys_tax_rate_input_account_code ON sys_tax_rate (input_account_code) WHERE input_account_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_sys_tax_rate_output_account_code ON sys_tax_rate (output_account_code) WHERE output_account_code IS NOT NULL;

