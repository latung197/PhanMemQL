-- Chạy lại được; chạy sau 45 (điều khoản thanh toán). Không khóa ngoại: liên kết bằng cột mã có chỉ mục.
--   * Khách hàng thuộc một nhóm (customer_group_code) và có điều khoản thanh toán mặc định (payment_term_code), cả hai tùy chọn.
--     credit_limit = hạn mức công nợ theo tiền hạch toán, 0 = không giới hạn. Mã số thuế không trùng giữa các khách hàng.
--   * Bảng giá bán: một loại tiền, hiệu lực từ ngày đến ngày (trống = không hết hạn), áp dụng cho một nhóm khách (trống = mọi khách).
--     Dòng giá: vật tư + đơn vị tính + số lượng từ (bậc giá) + đơn giá; một vật tư / đơn vị / bậc chỉ có một dòng trong một bảng giá.

CREATE TABLE IF NOT EXISTS erp_customer_group (
    code varchar(20) PRIMARY KEY,
    name varchar(100) NOT NULL,
    note varchar(300),
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_erp_customer_group_name ON erp_customer_group (lower(name));

CREATE TABLE IF NOT EXISTS erp_customer (
    code varchar(20) PRIMARY KEY,
    name varchar(200) NOT NULL,
    tax_code varchar(30),
    phone varchar(30),
    email varchar(100),
    contact_name varchar(100),
    address varchar(300),
    customer_group_code varchar(20),
    payment_term_code varchar(20),
    credit_limit numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_customer_credit_limit CHECK (credit_limit >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_erp_customer_tax_code ON erp_customer (tax_code) WHERE tax_code IS NOT NULL AND tax_code <> '';
CREATE INDEX IF NOT EXISTS ix_erp_customer_name ON erp_customer (lower(name));
CREATE INDEX IF NOT EXISTS ix_erp_customer_customer_group_code ON erp_customer (customer_group_code) WHERE customer_group_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_customer_payment_term_code ON erp_customer (payment_term_code) WHERE payment_term_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS erp_price_list (
    code varchar(20) PRIMARY KEY,
    name varchar(200) NOT NULL,
    currency_code varchar(10) NOT NULL,
    customer_group_code varchar(20),
    valid_from date NOT NULL,
    valid_to date,
    note varchar(300),
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_price_list_dates CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_erp_price_list_name ON erp_price_list (lower(name));
CREATE INDEX IF NOT EXISTS ix_erp_price_list_currency_code ON erp_price_list (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_price_list_customer_group_code ON erp_price_list (customer_group_code) WHERE customer_group_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_price_list_valid ON erp_price_list (valid_from, valid_to);

CREATE TABLE IF NOT EXISTS erp_price_list_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_code varchar(20) NOT NULL,
    material_code varchar(64) NOT NULL,
    uom_code varchar(30) NOT NULL,
    min_quantity numeric(18,4) NOT NULL DEFAULT 0,
    unit_price numeric(18,4) NOT NULL,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_price_list_line_price CHECK (unit_price >= 0),
    CONSTRAINT ck_erp_price_list_line_min_quantity CHECK (min_quantity >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_erp_price_list_line_key ON erp_price_list_line (price_list_code, material_code, uom_code, min_quantity);
CREATE INDEX IF NOT EXISTS ix_erp_price_list_line_material_code ON erp_price_list_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_price_list_line_uom_code ON erp_price_list_line (uom_code);
