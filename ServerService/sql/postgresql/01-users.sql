-- Audit user ids used to be varchar(5).
ALTER TABLE sys_users ALTER COLUMN createid TYPE varchar(20), ALTER COLUMN updateid TYPE varchar(20);
ALTER TABLE sys_role ALTER COLUMN createid TYPE varchar(20), ALTER COLUMN updateid TYPE varchar(20);
ALTER TABLE sys_user_role ALTER COLUMN createid TYPE varchar(20), ALTER COLUMN updateid TYPE varchar(20);
ALTER TABLE sys_role_command ALTER COLUMN createid TYPE varchar(20), ALTER COLUMN updateid TYPE varchar(20);
ALTER TABLE sys_user_command ALTER COLUMN createid TYPE varchar(20), ALTER COLUMN updateid TYPE varchar(20);

-- No foreign keys: tables are linked by their id/code columns and the API checks the links.
SELECT sys_drop_foreign_keys('sys_user_role', 'sys_role_command', 'sys_user_command');
-- Indexes on the link columns.
CREATE INDEX IF NOT EXISTS ix_sys_user_role_role ON sys_user_role (role_id);
CREATE INDEX IF NOT EXISTS ix_sys_role_command_menu ON sys_role_command (menuid0);
CREATE INDEX IF NOT EXISTS ix_sys_user_command_menu ON sys_user_command (menuid0);

-- Special rights on top of the five actions (SpecialRightCatalog), e.g. inv_receipt + VIEW_PRICE.
-- A row means granted. The user's own set applies when the user has an own matrix (sys_user_command).
CREATE TABLE IF NOT EXISTS sys_role_right (
    role_id integer NOT NULL,
    menuid0 varchar(64) NOT NULL,
    right_code varchar(50) NOT NULL,
    createtime timestamp,
    createid varchar(20),
    updatetime timestamp,
    updateid varchar(20),
    status varchar(1) NOT NULL DEFAULT '1',
    PRIMARY KEY (role_id, menuid0, right_code)
);

CREATE TABLE IF NOT EXISTS sys_user_right (
    user_id integer NOT NULL,
    menuid0 varchar(64) NOT NULL,
    right_code varchar(50) NOT NULL,
    createtime timestamp,
    createid varchar(20),
    updatetime timestamp,
    updateid varchar(20),
    status varchar(1) NOT NULL DEFAULT '1',
    PRIMARY KEY (user_id, menuid0, right_code)
);
