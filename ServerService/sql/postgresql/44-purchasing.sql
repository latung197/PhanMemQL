-- Mua hàng: phiếu yêu cầu mua hàng (bộ phận đề nghị mua) → đơn mua hàng (gửi nhà cung cấp) → phiếu nhập kho. Chạy lại được; chạy sau 42 và 43.
-- Cả hai chứng từ đi qua quy trình duyệt như mọi chứng từ nhưng KHÔNG ghi sổ (chỉ phiếu nhập kho mới làm đổi tồn).
-- Đơn mua hàng "lấy dữ liệu" từ phiếu yêu cầu mua đã duyệt: mỗi dòng ghi purchase_request_line_id (dòng yêu cầu mà nó đặt mua), đầu đơn
-- ghi purchase_request_code (danh sách số phiếu yêu cầu, cách nhau dấu phẩy). Phiếu nhập kho "lấy dữ liệu" từ đơn mua đã duyệt: mỗi dòng
-- ghi purchase_order_line_id, đầu phiếu ghi purchase_order_code. Số đã đặt của một dòng yêu cầu = tổng số lượng các dòng đơn mua trỏ tới nó
-- (đơn chưa hủy); số đã nhận của một dòng đơn = tổng số lượng các dòng phiếu nhập trỏ tới nó (phiếu chưa hủy): không lưu cột riêng, luôn
-- tính từ chứng từ sau, nên xóa hoặc hủy chứng từ sau thì số lượng tự trả lại. Không khóa ngoại theo quy ước dự án.

-- ---- Phiếu yêu cầu mua hàng ------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS erp_purchase_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    required_date date,
    warehouse_code varchar(20) NOT NULL,
    voucher_type varchar(100) NOT NULL,
    department_code varchar(20),
    requester_name varchar(200),
    supplier_code varchar(20),
    supplier_name varchar(200),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_request_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_purchase_request_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_unit_date ON erp_purchase_request (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_warehouse_code ON erp_purchase_request (warehouse_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_currency_code ON erp_purchase_request (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_department_code ON erp_purchase_request (department_code) WHERE department_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_supplier_code ON erp_purchase_request (supplier_code) WHERE supplier_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS erp_purchase_request_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_request_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_purchase_request_line_price CHECK (unit_price >= 0),
    UNIQUE (request_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_line_request ON erp_purchase_request_line (request_id);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_line_material_code ON erp_purchase_request_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_request_line_uom_code ON erp_purchase_request_line (uom_code);

-- ---- Đơn mua hàng ----------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS erp_purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    delivery_date date,
    warehouse_code varchar(20) NOT NULL,
    voucher_type varchar(100) NOT NULL,
    supplier_code varchar(20) NOT NULL,
    supplier_name varchar(200),
    payment_terms varchar(200),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    tax_rate_code varchar(20),
    tax_rate numeric(7,4) NOT NULL DEFAULT 0,
    sub_total numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    purchase_request_code varchar(500),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_order_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_purchase_order_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_unit_date ON erp_purchase_order (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_warehouse_code ON erp_purchase_order (warehouse_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_supplier_code ON erp_purchase_order (supplier_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_currency_code ON erp_purchase_order (currency_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_tax_rate_code ON erp_purchase_order (tax_rate_code) WHERE tax_rate_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS erp_purchase_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    note varchar(300),
    purchase_request_line_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_purchase_order_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_purchase_order_line_price CHECK (unit_price >= 0),
    UNIQUE (order_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_line_order ON erp_purchase_order_line (order_id);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_line_material_code ON erp_purchase_order_line (material_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_line_uom_code ON erp_purchase_order_line (uom_code);
CREATE INDEX IF NOT EXISTS ix_erp_purchase_order_line_request_line ON erp_purchase_order_line (purchase_request_line_id) WHERE purchase_request_line_id IS NOT NULL;

-- ---- Phiếu nhập kho lấy từ đơn mua hàng -----------------------------------------------------------------------------------
ALTER TABLE erp_goods_receipt ADD COLUMN IF NOT EXISTS purchase_order_code varchar(500);
ALTER TABLE erp_goods_receipt_line ADD COLUMN IF NOT EXISTS purchase_order_line_id bigint;
CREATE INDEX IF NOT EXISTS ix_erp_goods_receipt_line_purchase_order_line_id ON erp_goods_receipt_line (purchase_order_line_id) WHERE purchase_order_line_id IS NOT NULL;
