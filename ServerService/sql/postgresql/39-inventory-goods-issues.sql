-- Kho: phiếu xuất kho (đầu phiếu + dòng). Chạy lại được; chạy sau 20-inventory-goods-receipts.sql và 34-inventory-stock-ledger.sql.
-- Cấu trúc giống phiếu nhập kho (erp_goods_receipt): chỉ khác khách hàng / người nhận thay cho nhà cung cấp / người giao.
-- Ghi sổ: dịch vụ sổ kho (IStockLedger) ghi dòng xuất theo giá bình quân của kho, không dùng đơn giá trên phiếu; đơn giá và
-- thành tiền trên phiếu là giá xuất để tham khảo / in phiếu. Không khóa ngoại theo quy ước dự án.
CREATE TABLE IF NOT EXISTS erp_goods_issue (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    unit_code varchar(20) NOT NULL,
    document_date date NOT NULL,
    created_date date NOT NULL,
    warehouse_code varchar(20) NOT NULL,
    voucher_type varchar(100) NOT NULL,
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    exchange_rate numeric(18,6) NOT NULL DEFAULT 1,
    customer_name varchar(200),
    receiver_name varchar(200),
    note varchar(1000),
    status varchar(20) NOT NULL DEFAULT 'Draft',
    total_value numeric(18,2) NOT NULL DEFAULT 0,
    approved_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_goods_issue_status CHECK (status IN ('Draft','Pending','Approved','Posted','Cancelled')),
    CONSTRAINT ck_erp_goods_issue_rate CHECK (exchange_rate > 0)
);
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_unit_date ON erp_goods_issue (unit_code, document_date DESC);
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_warehouse ON erp_goods_issue (warehouse_code);
-- Mỗi cột *_code trỏ danh mục khác có index bắt đầu bằng chính cột đó (xóa ngoại tệ tra cột này).
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_currency ON erp_goods_issue (currency_code);

CREATE TABLE IF NOT EXISTS erp_goods_issue_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL,
    kind varchar(20) NOT NULL,
    line_no integer NOT NULL,
    material_code varchar(64) NOT NULL,
    material_name varchar(200) NOT NULL,
    uom_code varchar(30) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL,
    amount numeric(18,2) NOT NULL,
    lot_number varchar(64),
    position varchar(100),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_erp_goods_issue_line_kind CHECK (kind IN ('ITEM','MATERIAL')),
    CONSTRAINT ck_erp_goods_issue_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_erp_goods_issue_line_price CHECK (unit_price >= 0),
    UNIQUE (issue_id, kind, line_no)
);
CREATE INDEX IF NOT EXISTS ix_erp_goods_issue_line_issue ON erp_goods_issue_line (issue_id);
