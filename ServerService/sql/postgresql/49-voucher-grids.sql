-- Cấu hình lưới chi tiết chứng từ dùng chung toàn hệ thống: mỗi lưới (một tab của một chứng từ, ví dụ PNK_ITEMS, PNK_BOM) một dòng
-- trong sys_voucher_grid; các cột của lưới trong sys_voucher_grid_column. Bảng chỉ điều khiển phần TRÌNH BÀY (thứ tự, tiêu đề, độ rộng,
-- ẩn / hiện, số chữ số thập phân, gim bao nhiêu cột đầu); kiểu dữ liệu, tra cứu và cột bắt buộc vẫn do code khai báo.
-- Dữ liệu ban đầu do backend nạp từ Core/SeedData/voucher-grids.json khi khởi động (chỉ thêm cái còn thiếu, không ghi đè phần đã sửa).
-- Không khóa ngoại theo quy ước dự án. Chạy lại được.

CREATE TABLE IF NOT EXISTS sys_voucher_grid (
    code varchar(40) PRIMARY KEY,
    voucher_type varchar(20) NOT NULL,
    name varchar(200) NOT NULL,
    name_en varchar(200),
    tab_key varchar(20) NOT NULL DEFAULT 'items',
    tab_order integer NOT NULL DEFAULT 1,
    allow_add_row boolean NOT NULL DEFAULT true,
    allow_delete_row boolean NOT NULL DEFAULT true,
    pin_count integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_sys_voucher_grid_pin CHECK (pin_count >= 0 AND pin_count <= 5)
);
CREATE INDEX IF NOT EXISTS ix_sys_voucher_grid_voucher_type ON sys_voucher_grid (voucher_type, tab_order);

CREATE TABLE IF NOT EXISTS sys_voucher_grid_column (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_grid_code varchar(40) NOT NULL,
    field varchar(60) NOT NULL,
    header varchar(200) NOT NULL,
    header_en varchar(200),
    col_type varchar(20) NOT NULL,
    width integer,
    min_width integer,
    align varchar(10) NOT NULL DEFAULT 'left',
    decimals integer,
    is_required boolean NOT NULL DEFAULT false,
    is_read_only boolean NOT NULL DEFAULT false,
    is_visible boolean NOT NULL DEFAULT true,
    summary varchar(10),
    summary_format varchar(10),
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer,
    updated_at timestamptz,
    updated_by integer,
    CONSTRAINT ck_sys_voucher_grid_column_width CHECK (width IS NULL OR (width >= 40 AND width <= 800)),
    CONSTRAINT ck_sys_voucher_grid_column_min_width CHECK (min_width IS NULL OR (min_width >= 40 AND min_width <= 800)),
    CONSTRAINT ck_sys_voucher_grid_column_decimals CHECK (decimals IS NULL OR (decimals >= 0 AND decimals <= 6)),
    UNIQUE (voucher_grid_code, field)
);
CREATE INDEX IF NOT EXISTS ix_sys_voucher_grid_column_voucher_grid_code ON sys_voucher_grid_column (voucher_grid_code, sort_order);
